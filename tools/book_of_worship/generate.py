#!/usr/bin/env python3
"""Generates lib/features/church_texts/data/book_of_worship_data.dart from the
JSON files in texts/ (one per text, made from the pages of the online United
Methodist Book of Worship, translated into French and corrected by hand).

A text file has: slug, title, subtitle, url, copyright (the exact statement of
the page), icon, and blocks: [[kind, text], …] with kind H heading, P paragraph,
L leader, R people, N note, I list item.

Usage: python3 tools/book_of_worship/generate.py
"""
import glob
import json
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, "..", "..", "lib", "features", "church_texts", "data", "book_of_worship_data.dart")

KIND = {"H": "heading", "P": "p", "L": "leader", "R": "people", "N": "note", "I": "item"}


def q(s):
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n")
    return "'" + s + "'"


def camel(slug):
    parts = slug.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


# Order in the app.
order = [
    "basic_pattern", "litany_church_world", "ten_commandments", "confession_of_sin",
    "brief_great_thanksgiving", "blessings_closing", "word_and_table_1", "committal",
    "baptism_bcp", "christian_marriage_1", "death_and_resurrection", "sunday_order", "love_feast", "morning_praise", "evening_praise", "ash_wednesday", "good_friday", "healing_1", "ministry_dying", "ministry_after_death", "blessing_home", "birth_thanksgiving", "greetings_prayers", "ways_of_praying", "bibles_children", "covenant_renewal", "leaders_installation", "class_leaders", "christian_marriage_2", "great_thanksgiving_seasons", "holy_thursday", "palm_sunday", "easter_vigil", "tenebrae", "healing_2", "ministry_illness", "ministry_coma", "ministry_divorce", "farewell_pastor", "farewell_members", "appointment", "recognition_ordained", "selected_prayers", "consecration_building",
]
files = {os.path.basename(f)[:-5]: f for f in glob.glob(os.path.join(here, "texts", "*.json"))}
slugs = [s for s in order if s in files] + sorted(s for s in files if s not in order)

lines = [
    "import '../models/church_text.dart';",
    "",
    "// Generated by tools/book_of_worship/generate.py — correct the French in",
    "// tools/book_of_worship/texts/*.json, then run the script again.",
    "",
    "/// Extracts of The United Methodist Book of Worship (1992), published online by",
    "/// Discipleship Ministries (https://www.umcdiscipleship.org/book-of-worship).",
    "/// The Book of Worship is owned by The United Methodist Publishing House; each",
    "/// text carries the copyright statement of its page, as the site asks.",
    "///",
    "/// The French is a DeepL translation corrected by hand: to be proofread.",
    "class BookOfWorshipData {",
]
for slug in slugs:
    d = json.load(open(files[slug], encoding="utf-8"))
    source = d.get("source") or (
        "Livre de culte méthodiste uni (The United Methodist Book of Worship, 1992), "
        "propriété de The United Methodist Publishing House. Mention de droit d'auteur "
        f"de la page d'origine : « {d['copyright']} » "
        "Traduction française : ÉMU Compagnon (traduction automatique DeepL corrigée à la main, à relire)."
    )
    lines.append(f"  static const {camel(slug)} = ChurchText(")
    lines.append(f"    id: {q('bow_' + slug)},")
    lines.append(f"    title: {q(d['title'])},")
    lines.append(f"    subtitle: {q(d['subtitle'])},")
    lines.append(f"    icon: ChurchTextIcon.{d['icon']},")
    lines.append(f"    source: {q(source)},")
    lines.append(f"    sourceUrl: {q(d['url'])},")
    lines.append("    blocks: [")
    for kind, text in d["blocks"]:
        lines.append(f"      TextBlock.{KIND[kind]}({q(text)}),")
    lines.append("    ],")
    sw_path = os.path.join(here, "texts_sw", slug + ".json")
    if os.path.exists(sw_path):
        sw = json.load(open(sw_path, encoding="utf-8"))
        assert [k for k, _ in sw["blocks"]] == [k for k, _ in d["blocks"]], slug + ": les blocs swahili doivent suivre ceux du français"
        sw_source = (
            "The United Methodist Book of Worship (1992), mali ya The United Methodist Publishing House. "
            f"Taarifa ya hakimiliki ya ukurasa wa asili: « {d['copyright']} » "
            "Tafsiri ya Kiswahili: ÉMU Compagnon (tafsiri ya kompyuta ya DeepL kutoka Kifaransa, ya majaribio; "
            "haijakaguliwa na mzungumzaji wa Kiswahili)."
        )
        lines.append("    sw: ChurchText(")
        lines.append(f"      id: {q('bow_' + slug)},")
        lines.append(f"      title: {q(sw['title'])},")
        lines.append(f"      subtitle: {q(sw['subtitle'])},")
        lines.append(f"      icon: ChurchTextIcon.{d['icon']},")
        lines.append(f"      source: {q(sw_source)},")
        lines.append(f"      sourceUrl: {q(d['url'])},")
        lines.append("      blocks: [")
        for kind, text in sw["blocks"]:
            lines.append(f"        TextBlock.{KIND[kind]}({q(text)}),")
        lines.append("      ],")
        lines.append("    ),")
    lines.append("  );")
    lines.append("")
lines.append("  static const all = <ChurchText>[" + ", ".join(camel(s) for s in slugs) + "];")
lines.append("}")
open(out_path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(slugs)} textes écrits dans {os.path.relpath(out_path)}")
